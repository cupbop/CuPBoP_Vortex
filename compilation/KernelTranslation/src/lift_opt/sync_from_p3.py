#!/usr/bin/env python3
"""sync_from_p3.py <p3 root> <p4 root> [--check]: bring src/lift_opt up to date with the lift optimisation of experiments/p3 and experiments/p4.

What ends up here is built from those trees, never edited here:
  <p3>/tools/*.cpp                 the passes of J, the list comes from <p3>/tools/build.sh
  <p4>/tools/                      lodq.cpp, lodq.h, lover.h and the sources of <p4>/tools/build4.sh without DROP, p4plugin.cpp
  <p4>/patches/p2cfold_dq.patch    on p2cfold.cpp;  <p4>/patches/mkp3_hook.patch on mkp3.sh
  local.patch                      what exists only here: loops that created IR in heap-address or pointer-hash order (include/stable_order.h has the rule; lo-frag,
                                   p2c-alias byGuard, lo-pair repl), the lo-tree crash without a shared store, locta out of p4plugin.cpp. When one of the trees takes a change
                                   its hunk stops applying and the sync fails here: remove that hunk.
  pipeline.inc                     pipelines, gate, opt options, env defaults from mkp3.sh and mkp4.sh;  sources.cmake from the build scripts
schedule.inc is written by hand: no script holds the table of schedules.
--check compares instead of writing (exit 1 on any difference). A line of those scripts that no longer has the expected form is an error, never a silent default.

After a sync:
 1. Rebuild with the old objects removed (rm the objects of src/lift_opt and lift_opt_driver.cpp.o). Objects on the group's NFS can carry an mtime
    minutes in the future, and make then skips a source edited in that window: once the old pipeline string ran with no sign of it.
 2. tools/param_dyn.patch and p4/patches/translator_bar_merge.patch are not copies: they edit the translator. For a new version: patch -R with the old one, patch with the new one.
 3. Compare: CUPBOP_LIFT_OPT_DUMP against mkp4.sh (bytes behind the ModuleID line, which names mkp4.sh's temporary file), CUPBOP_LIFT_OPT_BC against the harness's device bitcode (bytes)."""
import os, re, shutil, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
PATCH = f"{HERE}/local.patch"
DROP = ("locta",)   # experiments/p4 recommends stopping it; its registration goes with local.patch
HEADERS = ("lodq.h", "lover.h")

def die(msg):
    sys.exit(f"sync_from_p3: {msg}")

def one(pat, text, what):
    m = re.findall(pat, text, re.M)
    if len(m) != 1:
        die(f"{what}: expected one match of {pat!r}, found {len(m)}")
    return m[0]

def pipeline_inc(mk, mk4):
    ic = one(r"\bIC='([^']+)'", mk, "IC")
    env = re.findall(r"\$\{([A-Z][A-Z0-9_]*):-([^}$]+)\}", one(r"^export (P2C_STAGES=.*)$", mk, "export line"))
    if not env:
        die("no env defaults on the export line")
    lp = one(r"^LP=([^;]+);", mk, "LP")
    light = one(r'^L="([^"]+)"$', mk, "L")
    gate = one(r"^grep -qE '([^']+)' \"\$1\" \|\| P3_PIPE=\$\{P3_PIPE:-\$L\}$", mk, "gate")
    full = one(r'^P=\$\{P3_PIPE:-"([^"]+)"\}$', mk, "P")
    if "${P4_PREHEXT:-}" not in full:
        die("mkp3.sh without the P4_PREHEXT hook")
    stage2 = one(r'-passes="(function\(\$P4[^"]*)"', mk4, "second opt of mkp4.sh")
    cmd = one(r"^opt (.*?) -load-pass-plugin=", mk, "opt line")
    cl = []
    for a in cmd.split():
        m = re.fullmatch(r"-([a-z0-9-]+)=(\S+)", a)
        if not m:
            die(f"opt option {a!r} is not -name=value")
        cl.append((m[1], m[2]))
    words = []
    for w in gate.split("|"):
        w = w.replace(r"\.", ".")
        if re.search(r"[\\^$*+?()\[\]{}]", w):
            die(f"gate alternative {w!r} is not a literal")
        words.append(w)
    q = lambda s: 'R"LO(' + s + ')LO"'
    o = ["// Generated by sync_from_p3.py from scripts/mkp3.sh and scripts/mkp4.sh: edit those scripts, not this file. The only place the pipelines are written down.",
         "// ${LP}, $IC, ${P4_PREHEXT:-}, $P4 and ${P4_POST:-} are expanded by lift_opt_driver.cpp as the scripts expand them.",
         f"static const char LIFT_OPT_IC[] = {q(ic)};",
         f"static const char LIFT_OPT_LP[] = {q(lp)};",
         f"static const char LIFT_OPT_LIGHT[] = {q(light)};",
         f"static const char LIFT_OPT_FULL[] = {q(full)};",
         "// mkp4.sh's second opt: reads what the first one printed, without the first one's options",
         f"static const char LIFT_OPT_STAGE2[] = {q(stage2)};",
         "// a module with none of these words keeps the light pipeline",
         "static const char *const LIFT_OPT_GATE[] = {" + ", ".join(f'"{w}"' for w in words) + "};",
         "// opt command-line options, set for the pipeline only",
         "static const struct { const char *name, *value; } LIFT_OPT_CL[] = {" + ", ".join(f'{{"{k}", "{v}"}}' for k, v in cl) + "};",
         "// environment defaults of the passes (an existing value stays)",
         "static const struct { const char *name, *value; } LIFT_OPT_ENV[] = {" + ", ".join(f'{{"{k}", "{v}"}}' for k, v in env) + "};", ""]
    return "\n".join(o)

def src_list(line):
    return re.findall(r"\bc (\w+)(?: (-D\S+))?(?= &| *$)", line)

def sources_cmake(bs, bs4):
    src = src_list(one(r"^(c liftopt .*)$", bs, "source line of build.sh"))
    src4 = [s for s in src_list(one(r"^(c lostale .*?)(?: & wait| *$)", bs4 + " ", "source line of build4.sh") + " &") if s[0] not in DROP]
    if not src or not src4:
        die("no sources on a build line")
    src += [("lodq", "")] + src4
    if not any(n == "p4plugin" for n, _ in src):
        die("p4plugin not on the build4.sh line")
    o = ["# Generated by sync_from_p3.py from tools/build.sh and tools/build4.sh: the pass sources and their defines (each keeps its own llvmGetPassPluginInfo, renamed).",
         "set(lift_opt_SOURCES"] + [f"  src/lift_opt/{n}.cpp" for n, _ in src] + [")"]
    for n, d in src:
        if d:
            o.append(f'set_source_files_properties(src/lift_opt/{n}.cpp PROPERTIES COMPILE_DEFINITIONS "{d[2:]}")')
    o.append('set_source_files_properties(src/lift_opt/p3plugin.cpp PROPERTIES COMPILE_DEFINITIONS "llvmGetPassPluginInfo=p3_all_info")')
    o.append('set_source_files_properties(src/lift_opt/p4plugin.cpp PROPERTIES COMPILE_DEFINITIONS "llvmGetPassPluginInfo=p4_all_info")')
    o.append('set_source_files_properties(${lift_opt_SOURCES} PROPERTIES COMPILE_OPTIONS "-O1;-g0;-w")')
    return "\n".join(o) + "\n", [n for n, _ in src]

def apply(tmp, patch, what):
    r = subprocess.run(["patch", "-s", "-p1", "-d", tmp, "-i", patch], capture_output=True, text=True)
    if r.returncode:
        die(f"{what} does not apply (a hunk taken over by one of the trees?):\n{r.stdout}{r.stderr}")

def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 2:
        die(__doc__)
    p3, p4 = args
    check = "--check" in sys.argv[1:]
    bs, bs4 = open(f"{p3}/tools/build.sh").read(), open(f"{p4}/tools/build4.sh").read()
    cm, names = sources_cmake(bs, bs4)
    want = {"sources.cmake": cm.encode()}
    with tempfile.TemporaryDirectory() as tmp:
        os.makedirs(f"{tmp}/tools"); os.makedirs(f"{tmp}/scripts")
        for n in names:
            src = p3 if os.path.exists(f"{p3}/tools/{n}.cpp") else p4
            shutil.copy(f"{src}/tools/{n}.cpp", f"{tmp}/tools/{n}.cpp")
        for h in HEADERS:
            shutil.copy(f"{p4}/tools/{h}", f"{tmp}/tools/{h}")
        shutil.copy(f"{p3}/scripts/mkp3.sh", f"{tmp}/scripts/mkp3.sh")
        apply(tmp, f"{p4}/patches/p2cfold_dq.patch", "p2cfold_dq.patch")
        apply(tmp, f"{p4}/patches/mkp3_hook.patch", "mkp3_hook.patch")
        if os.path.getsize(PATCH):
            apply(tmp, PATCH, "local.patch")
        want["pipeline.inc"] = pipeline_inc(open(f"{tmp}/scripts/mkp3.sh").read(), open(f"{p4}/scripts/mkp4.sh").read()).encode()
        for f in [f"{n}.cpp" for n in names] + list(HEADERS):
            want[f] = open(f"{tmp}/tools/{f}", "rb").read()
    bad = 0
    for f, b in want.items():
        p = f"{HERE}/{f}"
        old = open(p, "rb").read() if os.path.exists(p) else None
        if old == b:
            continue
        print(f"{'differs' if check else 'updated'}: {f}")
        bad += 1
        if not check:
            open(p, "wb").write(b)
    print(f"sync_from_p3: {len(want)} files, {bad} {'differ' if check else 'updated'}")
    return 1 if check and bad else 0

sys.exit(main())
