#!/usr/bin/env python3
"""sync_from_p3.py <p3 root> [--check]: bring src/lift_opt up to date with the lift optimisation developed in experiments/p3.

The pass sources are plain copies (never edit them here); everything else about the pipeline is derived from the two scripts that
define it, so that the translator cannot drift from them:
  <root>/tools/build.sh     the source list and each source's -D flags            -> sources.cmake
  <root>/scripts/mkp3.sh    pipelines, module gate, opt options, env defaults     -> pipeline.inc
--check compares instead of writing (exit 1 on any difference). A line of mkp3.sh or build.sh that no longer has the expected form
is an error, never a silent default.

After a sync:
 1. Rebuild with the old objects removed (rm the objects of src/lift_opt and lift_opt_driver.cpp.o). Objects on the group's NFS can carry an mtime
    minutes in the future, and make then skips a source edited in that window: once the old pipeline string ran with no sign of it.
 2. tools/param_dyn.patch is not a copy: it edits lifted_ir.cpp. For a new version: patch -R with the old one, patch with the new one.
 3. Compare: CUPBOP_LIFT_OPT_DUMP against mkp3.sh (bytes), CUPBOP_LIFT_OPT_BC against the harness's device bitcode (bytes)."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))

def die(msg):
    sys.exit(f"sync_from_p3: {msg}")

def one(pat, text, what):
    m = re.findall(pat, text, re.M)
    if len(m) != 1:
        die(f"{what}: expected one match of {pat!r}, found {len(m)}")
    return m[0]

def pipeline_inc(mk):
    ic = one(r"\bIC='([^']+)'", mk, "IC")
    env = re.findall(r"\$\{([A-Z][A-Z0-9_]*):-([^}$]+)\}", one(r"^export (P2C_STAGES=.*)$", mk, "export line"))
    if not env:
        die("no env defaults on the export line")
    lp = one(r"^LP=([^;]+);", mk, "LP")
    light = one(r'^L="([^"]+)"$', mk, "L")
    gate = one(r"^grep -qE '([^']+)' \"\$1\" \|\| P3_PIPE=\$\{P3_PIPE:-\$L\}$", mk, "gate")
    full = one(r'^P=\$\{P3_PIPE:-"([^"]+)"\}$', mk, "P")
    cmd = one(r"^opt (.*) -load-pass-plugin=", mk, "opt line")
    cl = []
    for a in cmd.split():
        m = re.fullmatch(r"-([a-z0-9-]+)=(\S+)", a)
        if not m:
            die(f"opt option {a!r} is not -name=value")
        cl.append((m[1], m[2]))
    words = []
    for w in gate.split("|"):
        w = w.replace(r"\.", ".")
        if re.search(r"[\\^$*+?()\[\]{}]", w):
            die(f"gate alternative {w!r} is not a literal")
        words.append(w)
    q = lambda s: 'R"LO(' + s + ')LO"'
    o = ["// Generated by sync_from_p3.py from scripts/mkp3.sh: edit that script, not this file. The only place the pipeline is written down.",
         "// ${LP} and $IC are expanded by lift_opt_driver.cpp as mkp3.sh expands them.",
         f"static const char LIFT_OPT_IC[] = {q(ic)};",
         f"static const char LIFT_OPT_LP[] = {q(lp)};",
         f"static const char LIFT_OPT_LIGHT[] = {q(light)};",
         f"static const char LIFT_OPT_FULL[] = {q(full)};",
         "// a module with none of these words keeps the light pipeline",
         "static const char *const LIFT_OPT_GATE[] = {" + ", ".join(f'"{w}"' for w in words) + "};",
         "// opt command-line options, set for the pipeline only",
         "static const struct { const char *name, *value; } LIFT_OPT_CL[] = {" + ", ".join(f'{{"{k}", "{v}"}}' for k, v in cl) + "};",
         "// environment defaults of the passes (an existing value stays)",
         "static const struct { const char *name, *value; } LIFT_OPT_ENV[] = {" + ", ".join(f'{{"{k}", "{v}"}}' for k, v in env) + "};", ""]
    return "\n".join(o)

def sources_cmake(bs):
    src = re.findall(r"\bc (\w+)(?: (-D\S+))?(?= &| *$)", one(r"^(c liftopt .*)$", bs, "source line"))
    if not src:
        die("no sources on the build.sh line")
    o = ["# Generated by sync_from_p3.py from tools/build.sh: the pass sources and their defines (each keeps its own llvmGetPassPluginInfo, renamed).",
         "set(lift_opt_SOURCES"] + [f"  src/lift_opt/{n}.cpp" for n, _ in src] + [")"]
    for n, d in src:
        if d:
            o.append(f'set_source_files_properties(src/lift_opt/{n}.cpp PROPERTIES COMPILE_DEFINITIONS "{d[2:]}")')
    o.append('set_source_files_properties(src/lift_opt/p3plugin.cpp PROPERTIES COMPILE_DEFINITIONS "llvmGetPassPluginInfo=p3_all_info")')
    o.append('set_source_files_properties(${lift_opt_SOURCES} PROPERTIES COMPILE_OPTIONS "-O1;-g0;-w")')
    return "\n".join(o) + "\n", [n for n, _ in src]

def main():
    if len(sys.argv) < 2:
        die(__doc__)
    root, check = sys.argv[1], "--check" in sys.argv[2:]
    mk = open(f"{root}/scripts/mkp3.sh").read()
    bs = open(f"{root}/tools/build.sh").read()
    cm, names = sources_cmake(bs)
    want = {"pipeline.inc": pipeline_inc(mk).encode(), "sources.cmake": cm.encode()}
    for n in names:
        want[f"{n}.cpp"] = open(f"{root}/tools/{n}.cpp", "rb").read()
    bad = 0
    for f, b in want.items():
        p = f"{HERE}/{f}"
        old = open(p, "rb").read() if os.path.exists(p) else None
        if old == b:
            continue
        print(f"{'differs' if check else 'updated'}: {f}")
        bad += 1
        if not check:
            open(p, "wb").write(b)
    print(f"sync_from_p3: {len(want)} files, {bad} {'differ' if check else 'updated'}")
    return 1 if check and bad else 0

sys.exit(main())
